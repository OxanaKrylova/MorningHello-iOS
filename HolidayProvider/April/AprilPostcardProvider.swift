import Foundation

struct AprilPostcardProvider {

    static func content(
        index: Int
    ) -> HolidayContent? {

        let images = (1...20).map {
            "April_\($0)"
        }

        let phrases = [
            "Пусть апрельское утро наполнит день свежестью, светом и хорошим настроением.",
            "Желаю тёплого весеннего дня, приятных прогулок и радостных открытий.",
            "Пусть апрель подарит новые силы, вдохновение и желание двигаться вперёд.",
            "Желаю замечать красоту весны и находить радость в каждом мгновении.",
            "Пусть солнечный свет, свежий воздух и добрые мысли украсят этот день.",
            "Желаю лёгкости, душевного тепла и прекрасного апрельского настроения.",
            "Пусть сегодняшний день принесёт приятные встречи и хорошие новости.",
            "Желаю больше времени для прогулок, отдыха и любимых занятий.",
            "Пусть весенняя природа вдохновляет мечтать, улыбаться и радоваться жизни.",
            "Желаю провести этот день интересно, легко и с удовольствием.",
            "Пусть апрель наполнит жизнь яркими красками и счастливыми событиями.",
            "Желаю солнечного настроения, спокойствия в душе и гармонии вокруг.",
            "Пусть каждый новый день этой весны приносит что-то доброе и красивое.",
            "Желаю вдохновения, бодрости и прекрасных мгновений на свежем воздухе.",
            "Пусть этот апрельский день станет поводом улыбнуться и почувствовать тепло весны.",
            "Желаю приятных впечатлений, интересных встреч и лёгкого настроения.",
            "Пусть весна подарит вам уютные минуты, добрые мысли и внутреннее спокойствие.",
            "Желаю наслаждаться солнцем, свежим воздухом и красотой пробуждающейся природы.",
            "Пусть сегодня найдётся время для отдыха, радости и маленьких удовольствий.",
            "Желаю светлого дня, весенней лёгкости и множества счастливых мгновений."
        ]

        let availableCount = min(
            images.count,
            phrases.count
        )

        guard availableCount > 0,
              index >= 0 else {
            return nil
        }

        let safeIndex = index % availableCount

        return HolidayContent(
            images: [
                images[safeIndex]
            ],
            phrases: [
                phrases[safeIndex]
            ],
            category: "Апрель"
        )
    }
}
