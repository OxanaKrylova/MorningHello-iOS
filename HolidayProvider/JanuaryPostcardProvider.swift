import Foundation

struct JanuaryPostcardProvider {

    static func content(
        index: Int
    ) -> HolidayContent? {

        let images = (1...20).map {
            "January_\($0)"
        }

        let phrases = [
            "Пусть январское утро будет спокойным, тёплым и по-домашнему уютным.",
            "Желаю доброго начала дня, ясных мыслей и приятных зимних мгновений.",
            "Пусть за окном будет зима, а в доме всегда живут тепло и хорошее настроение.",
            "Желаю уютного утра, душевного спокойствия и добрых людей рядом.",
            "Пусть сегодняшний день принесёт тепло, заботу и маленькие радости.",
            "Желаю начать день без спешки, с хорошими мыслями и приятными ожиданиями.",
            "Пусть январь подарит больше спокойных дней, тёплых встреч и счастливых моментов.",
            "Желаю хорошего настроения, уютного дома и приятных новостей.",
            "Пусть этот зимний день будет светлым, добрым и наполненным заботой.",
            "Желаю тепла в сердце, спокойствия в душе и прекрасного зимнего настроения.",
            "Пусть январское утро подарит бодрость, вдохновение и ощущение нового начала.",
            "Желаю уютного дня, добрых разговоров и времени для того, что радует.",
            "Пусть сегодня будет больше света, улыбок и приятных неожиданностей.",
            "Желаю спокойного зимнего утра и хорошего настроения на весь день.",
            "Пусть этот январский день принесёт гармонию, тепло и уверенность в хорошем.",
            "Желаю тёплого дома, верных друзей и маленьких поводов для радости.",
            "Пусть зима напоминает, как приятно иногда замедлиться и просто наслаждаться уютом.",
            "Желаю доброго дня, приятных встреч и душевного тепла.",
            "Пусть сегодняшний день будет спокойным, красивым и наполненным хорошими событиями.",
            "Желаю вам света в душе, тепла рядом и прекрасного январского настроения."
        ]

        let availableCount = min(
            images.count,
            phrases.count
        )

        guard availableCount > 0,
              index >= 0 else {
            return nil
        }

        let safeIndex =
            index % availableCount

        return HolidayContent(
            images: [
                images[safeIndex]
            ],
            phrases: [
                phrases[safeIndex]
            ],
            category: "Январь"
        )
    }
}
