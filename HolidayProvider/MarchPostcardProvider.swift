import Foundation

struct MarchPostcardProvider {

    static func content(
        index: Int
    ) -> HolidayContent? {

        let images = (1...18).map {
            "March_\($0)"
        }

        let phrases = [
            "Пусть мартовское утро наполнит дом светом, теплом и ароматом весны.",
            "Желаю красивого дня, добрых новостей и весеннего настроения.",
            "Пусть первые краски весны подарят вдохновение и радость.",
            "Желаю, чтобы сегодняшний день расцвёл приятными событиями.",
            "Пусть весна принесёт новые силы, светлые мысли и хорошие перемены.",
            "Желаю душевного тепла, спокойствия и цветов в каждом дне.",
            "Пусть это мартовское утро начнётся с улыбки и добрых ожиданий.",
            "Желаю больше солнечного света, красоты и счастливых мгновений.",
            "Пусть весеннее настроение останется с вами на весь день.",
            "Желаю, чтобы сегодня вас окружали забота, внимание и красота.",
            "Пусть март подарит вдохновение, лёгкость и желание мечтать.",
            "Желаю прекрасного дня, наполненного теплом и приятными встречами.",
            "Пусть каждый цветок напоминает, что весна уже совсем рядом.",
            "Желаю спокойного утра, гармонии в душе и радости в сердце.",
            "Пусть этот день будет таким же красивым и светлым, как весенний букет.",
            "Желаю добрых перемен, свежих идей и прекрасного настроения.",
            "Пусть весна постепенно наполняет жизнь теплом и яркими красками.",
            "Желаю начать этот день с хороших мыслей и ощущения приближающейся весны."
        ]

        let availableCount =
            min(
                images.count,
                phrases.count
            )

        guard availableCount > 0,
              index >= 0
        else {
            return nil
        }

        let safeIndex =
            index % availableCount

        return HolidayContent(
            images: [
                images[safeIndex]
            ],
            phrases: [
                phrases[safeIndex]
            ],
            category: "Март"
        )
    }
}
