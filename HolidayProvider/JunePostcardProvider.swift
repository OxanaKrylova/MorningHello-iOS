import Foundation

struct JunePostcardProvider {

    static func content(
        index: Int
    ) -> HolidayContent? {

        let images = (1...19).map {
            "June_\($0)"
        }

        let phrases = [
            "Пусть июньское утро наполнит день солнечным светом, теплом и хорошим настроением.",
            "Желаю тёплого летнего дня, лёгких мыслей и приятных встреч.",
            "Пусть начало лета подарит новые силы, вдохновение и радость.",
            "Желаю сегодня чаще улыбаться и замечать красоту вокруг.",
            "Пусть этот июньский день будет спокойным, светлым и добрым.",
            "Желаю свежего воздуха, ласкового солнца и времени для себя.",
            "Пусть лето начинается с хороших новостей и счастливых мгновений.",
            "Желаю уютного утра, неспешного дня и тёплого вечера.",
            "Пусть сегодня найдётся время для прогулки, отдыха и любимых занятий.",
            "Желаю, чтобы июнь подарил ощущение лёгкости и свободы.",
            "Пусть солнечный день наполнит сердце теплом и спокойствием.",
            "Желаю приятных разговоров, добрых людей рядом и прекрасного настроения.",
            "Пусть летняя природа вдохновляет мечтать и радоваться каждому дню.",
            "Желаю начать этот день с улыбки и закончить его с благодарностью.",
            "Пусть июнь принесёт больше света, тепла и маленьких радостей.",
            "Желаю лёгкого дня, интересных событий и душевного равновесия.",
            "Пусть сегодняшний день подарит красивое летнее воспоминание.",
            "Желаю наслаждаться каждым мгновением этого тёплого июня.",
            "Пусть утро станет началом чудесного дня, наполненного радостью и заботой."
        ]

        let availableCount = min(
            images.count,
            phrases.count
        )

        guard availableCount > 0,
              index >= 0 else {
            return nil
        }

        let safeIndex =
            index % availableCount

        return HolidayContent(
            images: [
                images[safeIndex]
            ],
            phrases: [
                phrases[safeIndex]
            ],
            category: "Июнь"
        )
    }
}
