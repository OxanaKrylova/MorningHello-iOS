import Foundation

struct AugustPostcardProvider {

    static func content(
        for date: Date = Date()
    ) -> HolidayContent? {

        let calendar = Calendar.current

        let components = calendar.dateComponents(
            [.month, .day],
            from: date
        )

        guard let month = components.month,
              let day = components.day,
              month == 8,
              (1...19).contains(day) else {
            return nil
        }

        let images = (1...19).map {
            "August_\($0)"
        }

        let phrases = [
            "Пусть августовское утро подарит спокойствие, лёгкость и ощущение настоящего отдыха.",
            "Желаю солнечного дня, приятных впечатлений и беззаботного летнего настроения.",
            "Пусть сегодня найдётся время для отдыха, любимых занятий и тёплых встреч.",
            "Желаю наслаждаться каждым мгновением августа и сохранять летнее тепло в сердце.",
            "Пусть этот день пройдёт без спешки, забот и лишних мыслей.",
            "Желаю ласкового солнца, свежего воздуха и прекрасного настроения.",
            "Пусть август подарит новые впечатления, радостные встречи и счастливые воспоминания.",
            "Желаю уютного утра, неспешного дня и приятного вечернего отдыха.",
            "Пусть сегодня вас окружают красивые места, добрые люди и летнее тепло.",
            "Желаю оставить повседневные заботы и позволить себе немного безмятежности.",
            "Пусть этот августовский день наполнится солнцем, радостью и маленькими приключениями.",
            "Желаю тёплого утра, лёгких мыслей и отдыха, который наполняет силами.",
            "Пусть сегодняшний день подарит ощущение свободы и летнего счастья.",
            "Желаю приятных прогулок, душевных разговоров и спокойного отдыха.",
            "Пусть августовское солнце согреет, а свежий ветер подарит бодрость и вдохновение.",
            "Желаю провести этот день там, где спокойно, красиво и хорошо на душе.",
            "Пусть летний отдых подарит новые силы, светлые мысли и добрые эмоции.",
            "Желаю наслаждаться августом, никуда не спешить и замечать красоту вокруг.",
            "Пусть это утро станет началом чудесного дня, наполненного отдыхом и радостью."
        ]

        let imageIndex = day - 1

        guard images.indices.contains(imageIndex),
              phrases.indices.contains(imageIndex) else {
            return nil
        }

        return HolidayContent(
            images: [
                images[imageIndex]
            ],
            phrases: [
                phrases[imageIndex]
            ],
            category: "Август"
        )
    }
}
