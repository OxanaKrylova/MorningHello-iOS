import Foundation

struct SeptemberPostcardProvider {

    static func content(
        for date: Date = Date()
    ) -> HolidayContent? {

        let calendar = Calendar.current

        let components = calendar.dateComponents(
            [.month, .day],
            from: date
        )

        guard let month = components.month,
              let day = components.day,
              month == 9,
              (1...18).contains(day) else {
            return nil
        }

        let images = (1...18).map {
            "September_\($0)"
        }

        let phrases = [
            "Пусть сентябрьское утро принесёт вдохновение, ясные мысли и добрые перемены.",
            "Желаю лёгкого начала нового сезона, интересных планов и уверенности в своих силах.",
            "Пусть этот сентябрь подарит новые возможности, приятные встречи и хорошие новости.",
            "Желаю начинать каждый осенний день с улыбки, спокойствия и веры в лучшее.",
            "Пусть новые планы вдохновляют, а каждый шаг приносит радость и удовлетворение.",
            "Желаю уютного утра, бодрого настроения и успешного начала всех важных дел.",
            "Пусть сентябрь наполнит жизнь свежими идеями, светлыми надеждами и тёплыми событиями.",
            "Желаю, чтобы учёба и работа приносили не только результаты, но и удовольствие.",
            "Пусть первый месяц осени станет началом добрых и долгожданных перемен.",
            "Желаю ясных целей, интересных открытий и людей, которые поддерживают и вдохновляют.",
            "Пусть сентябрьское солнце согреет, а новые задачи окажутся лёгкими и увлекательными.",
            "Желаю спокойно войти в новый ритм и находить время для отдыха и заботы о себе.",
            "Пусть сегодняшнее утро подарит силы для новых начинаний и уверенность в успехе.",
            "Желаю тёплого сентября, удачных решений и приятных результатов каждого дня.",
            "Пусть новые знания открывают возможности, а новые планы ведут к мечтам.",
            "Желаю сохранить летнее тепло в сердце и с радостью встретить осенние перемены."
        ]

        let imageIndex = day - 1

        guard images.indices.contains(imageIndex),
              phrases.indices.contains(imageIndex) else {
            return nil
        }

        return HolidayContent(
            images: [
                images[imageIndex]
            ],
            phrases: [
                phrases[imageIndex]
            ],
            category: "Сентябрь"
        )
    }
}
