import Foundation

struct JulyPostcardProvider {

    static func content(
        index: Int
    ) -> HolidayContent? {

        let images = (1...18).map {
            "July_\($0)"
        }

        let phrases = [
            "Пусть июльский день будет светлым, спокойным и наполненным маленькими радостями.",
            "Желаю тёплого солнца, лёгкого настроения и приятных летних впечатлений.",
            "Пусть сегодня найдётся время для отдыха, красивых видов и добрых мыслей.",
            "Желаю, чтобы этот летний день подарил улыбки, тепло и хорошую новость.",
            "Пусть июль наполнит сердце радостью, а каждый новый день приносит вдохновение.",
            "Желаю лёгкого ветерка, солнечного настроения и душевного спокойствия.",
            "Пусть сегодняшний день течёт неспешно и приносит только приятные события.",
            "Желаю летнего уюта, тёплых встреч и счастливых мгновений рядом с близкими.",
            "Пусть солнце согревает, вода освежает, а настроение остаётся прекрасным весь день.",
            "Желаю увидеть сегодня что-то красивое и сохранить это мгновение в памяти.",
            "Пусть июльское утро начнётся легко, а день сложится удачно и спокойно.",
            "Желаю прогулок у воды, добрых разговоров и настоящего летнего отдыха.",
            "Пусть этот день подарит ощущение свободы, лёгкости и тихого счастья.",
            "Желаю солнечных дорог, новых впечатлений и приятных открытий.",
            "Пусть лето радует яркими красками, свежим воздухом и хорошими людьми рядом.",
            "Желаю тёплого дня без спешки, забот и лишних переживаний.",
            "Пусть сегодня будет больше света, улыбок и поводов сказать: «Как хорошо!»",
            "Желаю, чтобы этот июльский день оставил после себя тёплое воспоминание."
        ]

        let availableCount = min(
            images.count,
            phrases.count
        )

        guard availableCount > 0,
              index >= 0 else {
            return nil
        }

        let safeIndex =
            index % availableCount

        return HolidayContent(
            images: [
                images[safeIndex]
            ],
            phrases: [
                phrases[safeIndex]
            ],
            category: "Июль"
        )
    }
}
