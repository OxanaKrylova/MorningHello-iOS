import SwiftUI
import SwiftData

struct MoodCheckInView: View {
    @Environment(\.dismiss) private var dismiss
    @Environment(\.modelContext) private var modelContext
    @StateObject private var store = MoodStore()

    @State private var showHistory = false
    @State private var showBreathingSquare = false

    private let backgroundColor = AppAdaptiveColor.warmFormBackground
    private let textColor = AppAdaptiveColor.text

    var body: some View {
        ZStack(alignment: .top) {
            backgroundColor
                .ignoresSafeArea()

            VStack(spacing: 0) {
                closeButton

                ScrollView {
                    VStack(spacing: 18) {
                        Text("Насколько вы спокойны сейчас?")
                            .font(
                                .system(
                                    .title2,
                                    design: .rounded
                                )
                                .weight(.bold)
                            )
                            .foregroundStyle(textColor)
                            .multilineTextAlignment(.center)

                        HStack(spacing: 6) {
                            ForEach(MoodLevel.allCases) { level in
                                moodButton(for: level)
                            }
                        }

                        if let selectedLevel = store.todayEntry?.moodLevel {
                            Text(
                                "\(selectedLevel.rawValue) – \(selectedLevel.title)"
                            )
                                .font(
                                    .system(
                                        size: 22,
                                        weight: .semibold,
                                        design: .rounded
                                    )
                                )
                                .foregroundStyle(selectedLevel.color)
                                .multilineTextAlignment(.center)
                        } else {
                            Text("0 – дзен, 4 – в панике")
                                .font(
                                    .system(
                                        size: 22,
                                        weight: .semibold,
                                        design: .rounded
                                    )
                                )
                                .foregroundStyle(.secondary)
                        }

                        if store.isSaveConfirmationVisible {
                            Label(
                                "Оценка сохранена",
                                systemImage: "checkmark.circle.fill"
                            )
                            .font(
                                .system(
                                    .subheadline,
                                    design: .rounded
                                )
                                .weight(.semibold)
                            )
                            .foregroundStyle(Color.green)
                            .transition(
                                .opacity.combined(
                                    with: .move(edge: .top)
                                )
                            )
                        }

                        if let errorMessage = store.errorMessage {
                            Text(errorMessage)
                                .font(.footnote)
                                .foregroundStyle(.red)
                                .multilineTextAlignment(.center)
                                .accessibilityLabel(
                                    L10n.format(
                                        "Ошибка. %@",
                                        errorMessage
                                    )
                                )
                        }

                        if let entry = store.todayEntry,
                           let level = entry.moodLevel,
                           let advice = CalmnessAdvice.text(
                               for: level,
                               localDay: entry.localDay
                           ) {
                            adviceCard(
                                text: advice,
                                level: level
                            )
                            .padding(.horizontal, -8)
                            .transition(
                                .opacity.combined(
                                    with: .move(edge: .top)
                                )
                            )
                        }
                    }
                    .padding(.horizontal, 20)
                    .padding(.bottom, 18)
                }
                .scrollIndicators(.hidden)

                HStack(spacing: 12) {
                    actionButton(
                        title: "Квадрат дыхания",
                        systemImage: "wind"
                    ) {
                        showBreathingSquare = true
                    }

                    actionButton(
                        title: "История",
                        systemImage: "chart.xyaxis.line"
                    ) {
                        showHistory = true
                    }
                    .accessibilityHint(
                        "Открывает график и список ваших отметок"
                    )
                }
                .padding(.horizontal, 20)
                .padding(.top, 12)
                .padding(.bottom, 24)
            }
            .padding(.top, 6)
            .frame(
                maxWidth: .infinity,
                maxHeight: .infinity,
                alignment: .top
            )
        }
        .frame(
            maxWidth: .infinity,
            maxHeight: .infinity,
            alignment: .top
        )
        .onAppear {
            store.configure(modelContext: modelContext)
            store.loadToday()
        }
        .sheet(isPresented: $showHistory) {
            MoodHistoryView()
        }
        .fullScreenCover(isPresented: $showBreathingSquare) {
            BreathingSquareView()
        }
    }

    private var closeButton: some View {
        HStack {
            Spacer()

            Button {
                dismiss()
            } label: {
                Image(systemName: "xmark")
                    .font(
                        .system(
                            size: 19,
                            weight: .bold
                        )
                    )
                    .foregroundStyle(AppAdaptiveColor.text)
                    .frame(
                        width: 46,
                        height: 46
                    )
                    .background(AppAdaptiveColor.secondaryBackground)
                    .clipShape(Circle())
                    .shadow(
                        color: AppAdaptiveColor.separator.opacity(0.20),
                        radius: 7,
                        x: 0,
                        y: 3
                    )
            }
            .accessibilityLabel("Закрыть оценку")
        }
        .padding(.horizontal, 4)
    }

    private func actionButton(
        title: String,
        systemImage: String,
        action: @escaping () -> Void
    ) -> some View {
        Button(action: action) {
            VStack(spacing: 8) {
                Image(systemName: systemImage)
                    .font(.system(size: 24, weight: .semibold))
                    .foregroundStyle(.orange)

                Text(L10n.text(title))
                    .font(
                        .system(
                            .headline,
                            design: .rounded
                        )
                        .weight(.semibold)
                    )
                    .foregroundStyle(textColor)
                    .multilineTextAlignment(.center)
                    .lineLimit(2)
                    .minimumScaleFactor(0.85)
            }
            .frame(
                maxWidth: .infinity,
                minHeight: 82
            )
            .padding(.horizontal, 8)
            .background(AppAdaptiveColor.secondaryBackground)
            .clipShape(
                RoundedRectangle(
                    cornerRadius: 22,
                    style: .continuous
                )
            )
            .shadow(
                color: AppAdaptiveColor.separator.opacity(0.20),
                radius: 8,
                x: 0,
                y: 4
            )
        }
        .buttonStyle(.plain)
    }

    private func adviceCard(
        text: String,
        level: MoodLevel
    ) -> some View {
        VStack(alignment: .leading, spacing: 12) {
            Label(
                "Что можно сделать сейчас",
                systemImage: "heart.text.square.fill"
            )
            .font(
                .system(
                    .headline,
                    design: .rounded
                )
                .weight(.bold)
            )
            .foregroundStyle(textColor)

            Text(text)
                .font(
                    .system(
                        size: 32,
                        weight: .semibold,
                        design: .rounded
                    )
                )
                .foregroundStyle(textColor)
                .lineSpacing(6)
                .fixedSize(
                    horizontal: false,
                    vertical: true
                )
        }
        .frame(
            maxWidth: .infinity,
            alignment: .leading
        )
        .padding(18)
        .background {
            LinearGradient(
                colors: [
                    AppAdaptiveColor.secondaryBackground,
                    level.color.opacity(0.24)
                ],
                startPoint: .topLeading,
                endPoint: .bottomTrailing
            )
        }
        .clipShape(
            RoundedRectangle(
                cornerRadius: 24,
                style: .continuous
            )
        )
        .overlay {
            RoundedRectangle(
                cornerRadius: 24,
                style: .continuous
            )
            .stroke(
                level.color.opacity(0.30),
                lineWidth: 1
            )
        }
        .shadow(
            color: level.color.opacity(0.12),
            radius: 8,
            x: 0,
            y: 4
        )
        .accessibilityElement(children: .combine)
    }

    private func moodButton(for level: MoodLevel) -> some View {
        let isSelected = store.todayEntry?.level == level.rawValue

        return Button {
            _ = store.save(level: level)
        } label: {
            VStack(spacing: 3) {
                Text(level.emoji)
                    .font(.system(size: 28))
                    .accessibilityHidden(true)

                Text("\(level.rawValue)")
                    .font(.system(.caption, design: .rounded).weight(.bold))
            }
            .frame(maxWidth: .infinity, minHeight: 62)
            .foregroundStyle(.primary)
            .background(level.color.opacity(isSelected ? 0.38 : 0.18))
            .overlay {
                RoundedRectangle(cornerRadius: 18, style: .continuous)
                    .stroke(
                        isSelected ? level.color : Color.clear,
                        lineWidth: 3
                    )
            }
            .clipShape(RoundedRectangle(cornerRadius: 18, style: .continuous))
        }
        .buttonStyle(.plain)
        .accessibilityLabel(level.accessibilityText)
        .accessibilityValue(
            isSelected
                ? L10n.text("Выбрано")
                : L10n.text("Не выбрано")
        )
        .accessibilityHint(
            L10n.text(
                "Дважды коснитесь, чтобы сохранить уровень спокойствия на сегодня"
            )
        )
    }
}

