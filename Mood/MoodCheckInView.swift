    static func text(
        for level: MoodLevel,
        localDay: String
    ) -> String? {
        let texts: [String]

        switch level {
        case .slightlyAnxious:
            texts = slightlyAnxious
        case .worried:
            texts = worried
        case .panic:
            texts = panic
        case .zen, .calm:
            return nil
        }

        let daySeed = localDay.unicodeScalars.reduce(0) {
            partialResult,
            scalar in

            (
                partialResult * 31 + Int(scalar.value)
            ) & 0x7fff_ffff
        }

        let index = (
            daySeed + level.rawValue * 17
        ) % texts.count

        return L10n.text(texts[index])
    }
